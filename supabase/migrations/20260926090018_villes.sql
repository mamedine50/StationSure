-- Stations : commune de référence (null = « Autre », la ville libre reste dans city).
alter table public.stations add column commune_code text references public.sn_communes (code) on delete set null;
comment on column public.stations.commune_code is 'Commune de référence (sn_communes). Null = localité « Autre » saisie librement dans city.';
update public.stations s
set commune_code = c.code, city = c.name
from public.sn_communes c
where s.commune_code is null
  and public.normaliser_localite(s.city) = public.normaliser_localite(c.name)
  and (select count(*) from public.sn_communes c2 where public.normaliser_localite(c2.name) = public.normaliser_localite(s.city)) = 1;

-- Localisation complète d'une station (commune, département, région).
create or replace function public.station_localite(p_station_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'city', s.city,
    'commune', c.name,
    'commune_code', c.code,
    'department', d.name,
    'department_code', d.code,
    'region', r.name,
    'region_code', r.code
  )
  from public.stations s
  left join public.sn_communes c on c.code = s.commune_code
  left join public.sn_departments d on d.code = c.department_code
  left join public.sn_regions r on r.code = d.region_code
  where s.id = p_station_id and s.organization_id in (select public.current_org_ids());
$$;
revoke all on function public.station_localite(uuid) from public, anon;
grant execute on function public.station_localite(uuid) to authenticated;

