create extension if not exists unaccent with schema extensions;

create table public.sn_regions (
  code text primary key,
  name text not null unique
);
create table public.sn_departments (
  code text primary key,
  name text not null,
  region_code text not null references public.sn_regions (code),
  unique (region_code, name)
);
create table public.sn_communes (
  code text primary key,
  name text not null,
  department_code text not null references public.sn_departments (code),
  unique (department_code, name)
);
comment on table public.sn_communes is 'Communes du Sénégal (référence, lecture seule). Code = région/département/commune en minuscules sans accent.';

-- Normalisation pour la recherche et le rattachement : minuscules, sans accents ni ponctuation.
create or replace function public.normaliser_localite(p text)
returns text
language sql
immutable
set search_path = ''
as $$
  select trim(both '-' from regexp_replace(lower(extensions.unaccent(coalesce(p, ''))), '[^a-z0-9]+', '-', 'g'));
$$;
revoke all on function public.normaliser_localite(text) from public, anon;
grant execute on function public.normaliser_localite(text) to authenticated, service_role;

